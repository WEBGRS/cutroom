"""Builds the demo media from public-domain / CC0 originals on Wikimedia Commons.

Usage: python tools/demo_media.py
Originals are cached in .scratch/demo-src; outputs and SOURCES.md go to public/showcase/media (and the promo's media folder).
"""
import json, os, subprocess, urllib.parse, urllib.request
from PIL import Image, ImageEnhance

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, '.scratch', 'demo-src')
UA = {'User-Agent': 'cutroom-demo-media/0.1 (webgrs@users.noreply.github.com)'}

# name, Commons file, author, licence, description
SOURCES = [
    ('lake.jpg', 'File:Lake@Canada(byTanviMalik).JPG', 'Tanvi Malik', 'CC0', 'Peyto Lake, Banff National Park'),
    ('village.jpg', 'File:Manarola(dettaglio).jpg', 'Jonas Lavoie-Levesque', 'CC0', 'Manarola, Cinque Terre'),
    ('cliffs.jpg', 'File:AcquaBeach@cliffs(byMonikaMajkowska).JPG', 'Monika Majkowska', 'CC0', 'Beach between two cliffs'),
    ('desert.mp4', 'File:Timelapse Joshua Tree Clouds and Sunset Near West Entrance.webm', 'NPS / Kristi Rugg', 'Public domain', 'Clouds over Joshua Tree National Park, time-lapse'),
]
SHOWCASE = ['lake.jpg', 'lake-graded.jpg', 'desert.mp4']
PROMO = ['lake.jpg', 'village.jpg', 'cliffs.jpg']


def original(title):
    os.makedirs(CACHE, exist_ok=True)
    q = urllib.parse.urlencode({'action': 'query', 'titles': title, 'prop': 'imageinfo', 'iiprop': 'url', 'format': 'json', 'formatversion': '2'})
    info = json.load(urllib.request.urlopen(urllib.request.Request(f'https://commons.wikimedia.org/w/api.php?{q}', headers=UA), timeout=60))
    url = info['query']['pages'][0]['imageinfo'][0]['url']
    path = os.path.join(CACHE, os.path.basename(urllib.parse.unquote(url.split('?')[0])))
    if not os.path.exists(path):
        open(path, 'wb').write(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=600).read())
    return path


def photo(src, out, w=2560, h=1440):
    im = Image.open(src).convert('RGB')
    # Centre crop to 16:9
    k = min(im.width / w, im.height / h)
    cw, ch = round(w * k), round(h * k)
    x, y = (im.width - cw) // 2, (im.height - ch) // 2
    im.crop((x, y, x + cw, y + ch)).resize((w, h), Image.LANCZOS).save(out, quality=88, optimize=True, progressive=True)


def graded(src, out):
    # Warm, slightly richer "after" for the before/after card
    im = Image.open(src).convert('RGB')
    r, g, b = im.split()
    r = r.point(lambda v: min(255, int(v * 1.06 + 6)))
    b = b.point(lambda v: int(v * 0.9))
    im = Image.merge('RGB', (r, g, b))
    im = ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(1.15)).enhance(1.08)
    im.save(out, quality=88, optimize=True, progressive=True)


def clip(src, out, start=2.0, dur=8.0):
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(start), '-t', str(dur), '-i', src, '-vf', 'fps=30,scale=1920:1080:flags=lanczos,format=yuv420p', '-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '20', '-movflags', '+faststart', out], check=True)


def main():
    work = os.path.join(CACHE, 'out')
    os.makedirs(work, exist_ok=True)
    for name, title, *_ in SOURCES:
        src = original(title)
        out = os.path.join(work, name)
        (clip if name.endswith('.mp4') else photo)(src, out)
        print(name, os.path.getsize(out) // 1024, 'KB')
    graded(os.path.join(work, 'lake.jpg'), os.path.join(work, 'lake-graded.jpg'))
    rows = '\n'.join(f'| `{n}` | {d} | {a} | {l} | https://commons.wikimedia.org/wiki/{urllib.parse.quote(t.replace(" ", "_"))} |' for n, t, a, l, d in SOURCES)
    notes = f'# Demo media sources\n\nGenerated by `tools/demo_media.py`. Photos are cropped to 16:9; the clip is 8 s from 0:02; `lake-graded.jpg` is a colour-graded copy of `lake.jpg`.\n\n| File | What | By | Licence | Original |\n|---|---|---|---|---|\n{rows}\n'
    for folder, names in (('showcase', SHOWCASE), ('cutroom', PROMO)):
        dest = os.path.join(ROOT, 'public', folder, 'media')
        if not os.path.isdir(os.path.join(ROOT, 'public', folder)):
            continue
        os.makedirs(dest, exist_ok=True)
        for n in names:
            with open(os.path.join(work, n), 'rb') as f, open(os.path.join(dest, n), 'wb') as g:
                g.write(f.read())
        with open(os.path.join(dest, 'SOURCES.md'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(notes)
        print('->', dest)


if __name__ == '__main__':
    main()
